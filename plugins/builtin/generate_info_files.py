def generate_one(entry):
    """Создаёт JSON-строку .info файла"""
    tid, name, ver, cat, mech, sig, inp, out, neurons, subcell, kin, func, refs = entry
    info = {
        "type_id": tid,
        "name": name,
        "version": ver,
        "category": cat,
        "mechanism_type": mech,
        "signaling": sig,
        "inputs": inp,
        "outputs": out,
        "neuron_types": neurons,
        "subcellular": subcell,
        "kinetics": kin,
        "function": func,
        "references": refs
    }
    return json.dumps(info, ensure_ascii=False, indent=2)

def main():
    os.makedirs(OUT, exist_ok=True)
    for entry in DATA:
        tid = entry[0]
        fname = f"mod_{tid:02d}_{entry[1].lower().replace(' ', '_').replace('/', '_').replace('(', '').replace(')', '')[:40]}.info"
        # Simplify: use mod_NN.info naming
        fname = f"mod_{tid:02d}.info"
        path = os.path.join(OUT, fname)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(generate_one(entry))
        print(f"  ✓ {fname}")

    print(f"\nСгенерировано {len(DATA)} .info файлов в {OUT}/")

if __name__ == '__main__':
    main()
